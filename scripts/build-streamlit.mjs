import { build } from 'vite'
import { createHash } from 'node:crypto'
import { readFile,writeFile,readdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
const root=fileURLToPath(new URL('../',import.meta.url))
await build({root,base:'./',build:{outDir:'streamlit_frontend',emptyOutDir:true}})
const hash=createHash('sha256')
async function hashDirectory(dir,relative=''){
 for(const entry of (await readdir(dir,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){
  const name=relative+entry.name,full=path.join(dir,entry.name)
  if(entry.isDirectory())await hashDirectory(full,name+'/')
  else{hash.update(name);hash.update(await readFile(full))}
 }
}
await hashDirectory(path.join(root,'streamlit_frontend'))
const revision=hash.digest('hex').slice(0,16)
await writeFile(path.join(root,'streamlit_release.py'),`# Generated by npm run build:streamlit; triggers a Streamlit release refresh.\nBUILD_REVISION = ${JSON.stringify(revision)}\n`)
console.log(`Streamlit frontend built: ${revision}`)
